/**
 * Regenerates `packages/core/src/forge/python/pyodide-runner-source.ts` from `pyodide-runner.mjs`
 * next to it. The `.mjs` file is the source of truth; the generated module carries it into the npm
 * package and the standalone binary (both ship JavaScript modules only, no loose files). At launch
 * the backend writes it into the Pyodide folder so the restricted child `node` can read it.
 * `tests/forge-python-pyodide-runner-source.test.ts` fails when the two drift apart.
 * Usage: node --experimental-strip-types scripts/pyodide-runner-source.ts
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = resolve("packages/core/src/forge/python");
const target = join(dir, "pyodide-runner-source.ts");
writeFileSync(
  target,
  `// Generated by scripts/pyodide-runner-source.ts from pyodide-runner.mjs. Do not edit.
/** The plain-JavaScript runner executed by the child \`node\` of the wasm Python backend. */
export const PYODIDE_RUNNER_SOURCE: string = ${JSON.stringify(readFileSync(join(dir, "pyodide-runner.mjs"), "utf8"))};
`,
);
execFileSync(resolve("node_modules/.bin/biome"), ["format", "--write", target], {
  stdio: "inherit",
});
