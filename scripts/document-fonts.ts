/**
 * Generates `fonts.css` and `coverage.json` of the document engine from the committed
 * `packages/core/assets/documents/fonts/sources.json` (spec 026 §5.5). Offline and deterministic.
 * Usage: node --experimental-strip-types scripts/document-fonts.ts [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

interface Source {
  family: string;
  style: string;
  weight: number;
  subset: string;
  file: string;
  range: string;
}

const root = resolve("packages/core/assets/documents/fonts");
const { sources } = JSON.parse(readFileSync(resolve(root, "sources.json"), "utf8")) as {
  sources: Source[];
};

const css = `${[
  "/* Generated by scripts/document-fonts.ts from sources.json. Do not edit. */",
  ...sources.map(
    (s) =>
      `@font-face { font-family: "${s.family}"; font-style: ${s.style}; font-weight: ${s.weight}; font-display: block; src: url("https://document.invalid/fonts/${s.file}") format("woff2"); unicode-range: ${s.range}; }`,
  ),
].join("\n")}\n`;

const coverage: Record<string, string[]> = {};
for (const s of sources) {
  const list = coverage[s.family] ?? [];
  for (const part of s.range.split(",").map((p) => p.trim()))
    if (!list.includes(part)) list.push(part);
  coverage[s.family] = list;
}
const json = `${JSON.stringify(coverage, null, 1)}\n`;

const targets: Array<[string, string]> = [
  [resolve(root, "../base/fonts.css"), css],
  [resolve(root, "coverage.json"), json],
];
if (process.argv.includes("--check")) {
  for (const [path, text] of targets) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== text) {
      console.error(`${path} is out of date: run scripts/document-fonts.ts`);
      process.exit(1);
    }
  }
} else for (const [path, text] of targets) writeFileSync(path, text);
