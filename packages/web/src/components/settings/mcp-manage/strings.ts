export const manageStrings = { en, es };
export type ManageStringKey = keyof typeof en;

/** The text for `key` in the current language, with `{name}` placeholders filled in. */
export const mgs = (key: ManageStringKey, params?: Record<string, string | number>): string =>
  format(manageStrings[locale.value][key], params);

/** "2 tools" / "1 tool": the singular and plural forms are separate strings. */
export const countText = (kind: "tool" | "resource" | "prompt", n: number): string =>
  mgs(`count.${kind}.${n === 1 ? "one" : "other"}` as ManageStringKey, { n });
