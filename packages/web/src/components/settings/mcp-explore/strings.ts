export const exploreStrings = { en, es };
export type ExploreStringKey = keyof typeof en;

/** The text for `key` in the current language, with `{name}` placeholders filled in. */
export const xs = (key: ExploreStringKey, params?: Record<string, string | number>): string =>
  format(exploreStrings[locale.value][key], params);

/** The message of a sync failure code (the server sends a code, never a raw error). */
export const syncErrorText = (code: string): string => {
  const key = `err.${code}` as ExploreStringKey;
  return key in en ? xs(key) : xs("err.internal");
};
